from typing import Any, Protocol

# Rows are camelCase dicts shaped like the contract types (AdminUser, AdminPosting, …).
Row = dict[str, Any]


class AdminRepository(Protocol):
    def stats(self) -> Row: ...
    def list_users(self, filters: Row, offset: int, limit: int) -> tuple[list[Row], int]: ...
    def get_user(self, user_id: str) -> Row | None: ...
    def set_user_lock(self, user_id: str, locked: bool, reason: str | None) -> None: ...
    def list_postings(self, filters: Row, offset: int, limit: int) -> tuple[list[Row], int]: ...
    def get_posting(self, posting_id: str) -> Row | None: ...
    def set_posting_hidden(self, posting_id: str, hidden: bool, reason: str | None) -> None: ...
    def list_companies(self, filters: Row, offset: int, limit: int) -> tuple[list[Row], int]: ...
    def get_company(self, company_id: str) -> Row | None: ...
    def set_company_verified(self, company_id: str, verified: bool) -> None: ...
    def list_audit(self, filters: Row, offset: int, limit: int) -> tuple[list[Row], int]: ...
