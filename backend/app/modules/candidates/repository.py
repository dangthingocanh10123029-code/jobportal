from typing import Protocol

from app.modules.candidates.domain import CandidateProfile


class CandidateRepository(Protocol):
    def profile(self, user_id: str) -> CandidateProfile | None: ...
    def update_profile(self, user_id: str, values: dict) -> CandidateProfile | None: ...
    def applicant_profile(self, application_id: str) -> CandidateProfile | None: ...
    def toggle_saved(self, user_id: str, posting_id: str) -> bool | None: ...
    def saved(self, user_id: str) -> list[dict]: ...
    def saved_ids(self, user_id: str) -> list[str]: ...
