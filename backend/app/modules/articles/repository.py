from typing import Any, Protocol

Row = dict[str, Any]


class ArticleRepository(Protocol):
    """Rows are camelCase: ArticleSummary fields (+ content for get_*, + status for admin reads)."""

    def list_published(self, category: str | None, q: str | None, offset: int, limit: int) -> tuple[list[Row], int]: ...
    def get_published(self, slug: str) -> Row | None: ...
    def related(self, article_id: str, category: str, limit: int) -> list[Row]: ...
    def increment_views(self, slug: str) -> None: ...
    def list_admin(self, status: str | None, offset: int, limit: int) -> tuple[list[Row], int]: ...
    def get_admin(self, article_id: str) -> Row | None: ...
    def save(self, article_id: str | None, title: str, slug: str, excerpt: str, category: str, content: str) -> str:
        """Insert (article_id None) or update; a taken slug gets -2, -3…; returns the id. ADMIN only."""
        ...
    def set_published(self, article_id: str, published: bool) -> None:
        """Also writes the ARTICLE_PUBLISHED / ARTICLE_UNPUBLISHED audit entry. ADMIN only."""
        ...
